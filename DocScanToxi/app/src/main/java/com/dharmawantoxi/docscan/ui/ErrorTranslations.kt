    fun english(message: String): String {
        messages[message]?.let { return it }
        val merge = Regex("^File ke-([0-9]+) tidak dapat digabung: (.*)$").matchEntire(message)
        if (merge != null) return "File ${merge.groupValues[1]} could not be merged: ${english(merge.groupValues[2])}"
        val prefixes = listOf(
            "Nama dalam ZIP ambigu: " to "Ambiguous ZIP name: ",
            "Nama dalam ZIP duplikat: " to "Duplicate ZIP name: ",
            "Jalur ZIP tidak aman: " to "Unsafe ZIP path: ",
            "Isi ZIP rusak: " to "Damaged ZIP content: ",
            "Nama tujuan sudah ada: " to "Destination name already exists: ",
            "Tidak dapat membuat " to "Unable to create ",
            "Bagian Office tidak ditemukan: " to "Office part not found: "
        )
        for ((prefix, translated) in prefixes) {
            if (message.startsWith(prefix)) return translated + message.removePrefix(prefix)
        }
        return message
    }
